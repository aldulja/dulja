-- 0065_create_pos_cashier.sql — the till credential (§4.6.3; spec:1324, 2097; LEGACY-025, 026, 028).
-- The PIN is the ONLY credential this application hashes and it is NEVER a login: no route compares one,
-- and verification happens at the till against the down-synced mirror.

-- ── 1. the table ────────────────────────────────────────────────────────────────────────────────────
create table app.pos_cashier (
  principal_id     uuid primary key references app.principal(id),   -- keyed on the human principal (spec:2097); no separate id (NO_ID_TABLES)
  tenant_id        uuid not null references app.tenant(id),
  company_id       uuid not null,
  employee_id      uuid not null,
  branch_id        uuid not null,
  pin_hash         text not null,                                    -- Argon2id PHC string, per-cashier salt (spec:1324); written only by the PIN endpoints
  pin_updated_at   timestamptz not null default now(),
  snapshot         jsonb not null default '{}'::jsonb,               -- projection: { "codes": [...], "limits": {...}, "revision": n } — §4.6.3, ADR 0061
  snapshot_at      timestamptz,
  revision         bigint not null default 0,                        -- catalogue revision (§4.10.2)
  revoked_at       timestamptz,
  created_at       timestamptz not null default now(),
  unique (tenant_id, principal_id),
  foreign key (tenant_id, company_id)  references app.company(tenant_id, id),
  foreign key (tenant_id, employee_id) references app.employee(tenant_id, id),
  foreign key (tenant_id, branch_id)   references app.dimension_value(tenant_id, id)
);
comment on column app.pos_cashier.snapshot is
  'A PROJECTION regenerated by app.refresh_pos_cashier (0067). Never edited by hand; never read by the server to make a decision (spec:1324, D14).';

call app_meta.enable_tenant_rls('app.pos_cashier');
-- No attach_audit: AUDIT_EXEMPT (§3.5.3). An audited before/after image of pin_hash is a second copy of a
-- credential sitting in a table with a different read gate, and the snapshot is derived data (LEGACY-028).

-- ── 2. catalogue revision — the row is a down-synced stream (§4.10.2, 6A's trigger) ──────────────────
create trigger catalogue_revision before insert or update on app.pos_cashier
  for each row execute function app.catalogue_revision('cashier');

-- ── 3. revocation is visible to a disconnected till (spec:1324, 2090; test 34) ───────────────────────
-- 6A's generic trigger tombstones an ARCHIVAL; a cashier is REVOKED, and revoked_at is a different column,
-- so the transition gets its own AFTER trigger. It fires on the null -> value transition only, so a second
-- revoke writes no second tombstone and the till's cursor advances once.
-- The `on conflict` is not defensive padding: app.catalogue_tombstone carries `unique (stream, row_id)`
-- (6A's 0059) and 6A's own trigger upserts for the same reason -- "a resurrection is an upsert, not a
-- second death". Reinstating a cashier is `revoked_at = null` followed by a later revoke, and without the
-- clause that second revoke aborts the whole reinstatement transaction on the unique key.
create function app.pos_cashier_tombstone() returns trigger language plpgsql as $$
begin
  insert into app.catalogue_tombstone (tenant_id, company_id, stream, row_id, revision, branch_id)
  values (new.tenant_id, new.company_id, 'cashier', new.principal_id, new.revision, new.branch_id)
  on conflict (stream, row_id) do update set revision = excluded.revision, branch_id = excluded.branch_id;
  return null;
end $$;

create trigger pos_cashier_tombstone after update of revoked_at on app.pos_cashier
  for each row when (old.revoked_at is null and new.revoked_at is not null)
  execute function app.pos_cashier_tombstone();

-- ── 4. the down-sync stream 6A's readCatalogue calls (§4.10.2; 6A:2913) ──────────────────────────────
-- 6A's readCatalogue probes `to_regclass('app.pos_cashier')` and, when it is not null, executes
--   select ... from app.pos_cashier_sync($company, $branch, $since)
-- so this function MUST ship in the same migration as the table, or every GET /v1/sync/catalogue and 6A's
-- own readCatalogue suite fail with "function app.pos_cashier_sync(uuid, uuid, bigint) does not exist" the
-- moment 0065 is applied. 6A fixes the signature: (p_company_id uuid, p_branch_id uuid, p_since bigint)
-- returns table (id uuid, revision bigint, row jsonb). Naming a function rather than the table keeps 6A from
-- hard-coding column names it does not own.
--
-- A REVOKED cashier is excluded, exactly as 6A excludes `archived_at is not null` from every live leg: the
-- revoke bumps the revision AND writes the tombstone at the same revision, so admitting the live row would
-- put an upsert and a delete for one id in one window and the till's apply order would decide by accident.
-- `pin_hash` DOES travel -- the till verifies the PIN offline against this mirror (spec:1324) -- and
-- `tenant_id` does not, matching 6A's `to_jsonb(i) - 'tenant_id'`.
create function app.pos_cashier_sync(p_company_id uuid, p_branch_id uuid, p_since bigint)
returns table (id uuid, revision bigint, "row" jsonb)
language sql stable as $$
  select c.principal_id, c.revision, (to_jsonb(c) - 'tenant_id') || jsonb_build_object(
    'employee_number', e.employee_number, 'revision', c.revision::text)
    from app.pos_cashier c
    join app.employee e on e.tenant_id = c.tenant_id and e.company_id = c.company_id and e.id = c.employee_id
   where c.company_id = p_company_id
     and c.branch_id = p_branch_id
     and c.revision > p_since
     and c.revoked_at is null
$$;
grant execute on function app.pos_cashier_sync(uuid, uuid, bigint) to app_rw;

-- ── 5. lookups the sync apply and the compare job make on every batch ────────────────────────────────
create index pos_cashier_branch_idx on app.pos_cashier (company_id, branch_id) where revoked_at is null;
create index pos_cashier_employee_idx on app.pos_cashier (employee_id);
create index pos_cashier_cursor_idx on app.pos_cashier (company_id, branch_id, revision);
