    for (const [path, item] of Object.entries(document.paths ?? {}))
      for (const method of ["post", "put", "patch", "delete"] as const) {
        const operation = (item as Record<string, { parameters?: { name: string }[] }>)[method];
        // Public redemption has no actor or idempotency cache: its bearer code is spent exactly once.
        if (operation && path !== "/v1/sync/enrol")
          expect(
            operation.parameters?.map((parameter) => parameter.name),
            `${method} ${path}`,
          ).toContain("Idempotency-Key");
      }
